const fs = require("fs");
const path = require("path");
const { withDangerousMod } = require("expo/config-plugins");

const PODFILE_VAR = "$RNFirebaseAnalyticsWithoutAdIdSupport = true";
const INSERT_AFTER_PATTERN = /^platform :ios,.*$/m;

/**
 * Sets the $RNFirebaseAnalyticsWithoutAdIdSupport global in ios/Podfile so
 * @react-native-firebase/analytics resolves the IdentitySupport-free variant
 * of FirebaseAnalytics/GoogleAppMeasurement (no IDFA linkage). Must run
 * before the app target block, since RN Firebase reads the variable during
 * pod resolution. Lives as a config plugin because ios/ is gitignored and
 * regenerated by prebuild: a direct Podfile edit never reaches a shipped build.
 */
module.exports = function withFirebaseNoAdIdSupport(config) {
  return withDangerousMod(config, [
    "ios",
    (c) => {
      const podfilePath = path.join(c.modRequest.platformProjectRoot, "Podfile");
      if (!fs.existsSync(podfilePath)) {
        throw new Error(
          `withFirebaseNoAdIdSupport: Podfile not found at ${podfilePath}`
        );
      }

      const contents = fs.readFileSync(podfilePath, "utf8");

      if (contents.includes(PODFILE_VAR)) {
        return c;
      }

      if (!INSERT_AFTER_PATTERN.test(contents)) {
        throw new Error(
          "withFirebaseNoAdIdSupport: could not find `platform :ios, ...` line in Podfile to anchor the insertion."
        );
      }

      const updated = contents.replace(INSERT_AFTER_PATTERN, (match) => `${match}\n${PODFILE_VAR}`);
      fs.writeFileSync(podfilePath, updated);

      return c;
    },
  ]);
};
