// Permissions injected by transitive libraries that this app never exercises.
// expo-contacts always requests WRITE_CONTACTS even though the SOS emergency-
// contact picker only reads contacts (app/emergency-contacts.tsx), and
// expo-camera only adds RECORD_AUDIO when recordAudioAndroid is left at its
// true default; app.json already sets recordAudioAndroid: false, but a stale
// or future prebuild could reintroduce it, so it is stripped here too.
// tools:node="remove" is required (not just omitting the entry) because the
// manifest merger re-adds whatever the library manifests declare; a plain
// array edit would be overwritten on the next merge.
// zerospike ships no advertising SDK and never reads an advertising ID. Stripping
// AD_ID guarantees the Play advertising-ID declaration stays "no" even if a
// library (or a future dependency) adds the permission transitively.
const BADGE_PERMISSIONS = [
  // expo-notifications bundles me.leolin:ShortcutBadger, whose AAR manifest
  // declares one read/write pair per launcher vendor. The app never calls
  // setBadgeCountAsync/getBadgeCountAsync and sends no remote push with a
  // badge field, so none of these is exercised.
  "com.sec.android.provider.badge.permission.READ",
  "com.sec.android.provider.badge.permission.WRITE",
  "com.htc.launcher.permission.READ_SETTINGS",
  "com.htc.launcher.permission.UPDATE_SHORTCUT",
  "com.sonyericsson.home.permission.BROADCAST_BADGE",
  "com.sonymobile.home.permission.PROVIDER_INSERT_BADGE",
  "com.anddoes.launcher.permission.UPDATE_COUNT",
  "com.majeur.launcher.permission.UPDATE_BADGE",
  "com.huawei.android.launcher.permission.CHANGE_BADGE",
  "com.huawei.android.launcher.permission.READ_SETTINGS",
  "com.huawei.android.launcher.permission.WRITE_SETTINGS",
  "android.permission.READ_APP_BADGE",
  "com.oppo.launcher.permission.READ_SETTINGS",
  "com.oppo.launcher.permission.WRITE_SETTINGS",
  "me.everything.badger.permission.BADGE_COUNT_READ",
  "me.everything.badger.permission.BADGE_COUNT_WRITE",
];

const REMOVED_PERMISSIONS = [
  "android.permission.WRITE_CONTACTS",
  "android.permission.RECORD_AUDIO",
  "com.google.android.gms.permission.AD_ID",
  // Privacy Sandbox variant of the same thing, pulled in transitively through
  // androidx.privacysandbox.ads:ads-adservices. Play's advertising-ID
  // declaration counts this one too, so stripping only the gms permission
  // still forces the "uses advertising ID" answer. The app runs no ads and
  // never calls the AdServices APIs.
  "android.permission.ACCESS_ADSERVICES_AD_ID",
  // The expo prebuild template writes it into the app manifest. The app draws
  // no overlay windows; reminders use a full-screen-intent notification and the
  // alarm ring activity, which need no overlay permission.
  "android.permission.SYSTEM_ALERT_WINDOW",
  ...BADGE_PERMISSIONS,
];

/**
 * Pure manifest transform: marks every REMOVED_PERMISSIONS entry with
 * tools:node="remove" (adding the entry when the app manifest does not list
 * it, so the merger drops the library-declared copy). Mutates and returns the
 * given manifest object (the `manifest` key of a parsed AndroidManifest.xml).
 */
function trimManifestPermissions(manifest) {
  manifest.$ = manifest.$ || {};
  manifest.$["xmlns:tools"] = "http://schemas.android.com/tools";

  manifest["uses-permission"] = manifest["uses-permission"] || [];

  for (const permission of REMOVED_PERMISSIONS) {
    const existing = manifest["uses-permission"].find(
      (p) => p.$["android:name"] === permission
    );
    if (existing) {
      existing.$["tools:node"] = "remove";
    } else {
      manifest["uses-permission"].push({
        $: { "android:name": permission, "tools:node": "remove" },
      });
    }
  }
  return manifest;
}

/**
 * Removes Android permissions that ship by default with expo-contacts,
 * expo-camera, expo-notifications and the prebuild template but that zerospike
 * never actually uses, to avoid an "unused sensitive permission" flag during
 * Play review. Lives as a config plugin because android/ is gitignored and
 * regenerated by prebuild: a direct AndroidManifest.xml edit never reaches a
 * shipped build.
 */
module.exports = function withAndroidPermissionTrim(config) {
  const { withAndroidManifest } = require("expo/config-plugins");
  return withAndroidManifest(config, (c) => {
    trimManifestPermissions(c.modResults.manifest);
    return c;
  });
};

module.exports.trimManifestPermissions = trimManifestPermissions;
module.exports.REMOVED_PERMISSIONS = REMOVED_PERMISSIONS;
