const fs = require("fs");
const path = require("path");
const { IOSConfig, WarningAggregator, withAppDelegate, withInfoPlist, withXcodeProject } = require("expo/config-plugins");

// Apps built with the iOS 27 SDK abort at launch unless they adopt the UIScene
// life cycle (UIKit _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption).
// Expo 57.0.23+ ships ExpoAppSceneDelegate and ExpoReactNativeFactoryProvider,
// but the SDK 57 template and prebuild-config never wire them up; this plugin
// produces the same shape as the SDK 58 bare template: a SceneDelegate that
// creates the window and starts React Native, an AppDelegate that only builds
// the factory, and a scene manifest in Info.plist.

const SCENE_DELEGATE_FILE = "SceneDelegate.swift";
const SCENE_DELEGATE_MARKER = "// Generated by plugins/withSceneLifecycle.js";
const SCENE_DELEGATE_SOURCE = `${SCENE_DELEGATE_MARKER}; edit the plugin, not this file.
internal import Expo
import UIKit

@objc(SceneDelegate)
class SceneDelegate: ExpoAppSceneDelegate {
  private static var startedReactNative = false

  override func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    // iPadOS can disconnect the only scene (its window closed) and connect a new
    // one while the process, and React Native with it, keeps running. Starting
    // React Native again would mount a second surface in the same runtime, so
    // the running window moves to the new scene instead: whole, so a modal it
    // is presenting and its background color come along.
    guard SceneDelegate.startedReactNative,
      let windowScene = scene as? UIWindowScene,
      let provider = UIApplication.shared.delegate as? ExpoReactNativeFactoryProvider,
      let previousWindow = provider.window,
      previousWindow.rootViewController != nil
    else {
      super.scene(scene, willConnectTo: session, options: connectionOptions)
      SceneDelegate.startedReactNative = window?.rootViewController != nil
      return
    }

    previousWindow.windowScene = windowScene
    self.window = previousWindow
    provider.window = previousWindow
    previousWindow.makeKeyAndVisible()

    if !connectionOptions.urlContexts.isEmpty {
      self.scene(scene, openURLContexts: connectionOptions.urlContexts)
    }
    connectionOptions.userActivities.forEach { self.scene(scene, continue: $0) }
#if os(iOS)
    if let shortcutItem = connectionOptions.shortcutItem {
      self.windowScene(windowScene, performActionFor: shortcutItem) { _ in }
    }
#endif
  }

  override func sceneDidBecomeActive(_ scene: UIScene) {
    super.sceneDidBecomeActive(scene)
    // A key overlay window (alert, dev banner) can be hidden without UIKit
    // promoting another one, leaving the scene with no key window; RN's
    // RCTKeyWindow() and Expo's currentViewController() then find nothing to
    // present from. Only fill that gap: a visible alert that is key keeps it.
    guard let window, let windowScene = scene as? UIWindowScene, windowScene.keyWindow == nil else {
      return
    }
    window.makeKey()
  }
}
`;

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: "Default Configuration",
        UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
      },
    ],
  },
};

const PROVIDER = "ExpoReactNativeFactoryProvider";
const CLASS_DECL = /class AppDelegate:\s*ExpoAppDelegate\s*\{/;
const WINDOW_BLOCK =
  /\n#if os\(iOS\) \|\| os\(tvOS\)\n[ \t]*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n([\s\S]*?)[ \t]*factory\.startReactNative\(\s*withModuleName:\s*"main",\s*in:\s*window,\s*launchOptions:\s*launchOptions\)\n#endif\n/;
const LINKING_OVERRIDE =
  /\n[ \t]*\/\/ Linking API\n[ \t]*public override func application\(\n[ \t]*_ app: UIApplication,\n[ \t]*open url: URL,\n[ \t]*options: \[UIApplication\.OpenURLOptionsKey: Any\] = \[:\]\n[ \t]*\) -> Bool \{\n[ \t]*return super\.application\(app, open: url, options: options\) \|\| RCTLinkingManager\.application\(app, open: url, options: options\)\n[ \t]*\}\n/;
const UNIVERSAL_LINK_OVERRIDE =
  /\n[ \t]*\/\/ Universal Links\n[ \t]*public override func application\(\n[ \t]*_ application: UIApplication,\n[ \t]*continue userActivity: NSUserActivity,\n[ \t]*restorationHandler: @escaping \(\[UIUserActivityRestoring\]\?\) -> Void\n[ \t]*\) -> Bool \{\n[ \t]*let result = RCTLinkingManager\.application\(application, continue: userActivity, restorationHandler: restorationHandler\)\n[ \t]*return super\.application\(application, continue: userActivity, restorationHandler: restorationHandler\) \|\| result\n[ \t]*\}\n/;

function fail(message) {
  throw new Error(`withSceneLifecycle: ${message}`);
}

function warnIOS(message) {
  WarningAggregator.addWarningIOS("withSceneLifecycle", message);
}

function transformAppDelegate(src, warn = warnIOS) {
  let out = src;

  if (!out.includes(PROVIDER)) {
    if (!CLASS_DECL.test(out)) fail("`class AppDelegate: ExpoAppDelegate {` not found in AppDelegate.swift.");
    out = out.replace(CLASS_DECL, `class AppDelegate: ExpoAppDelegate, ${PROVIDER} {`);
  }

  const windowBlock = out.match(WINDOW_BLOCK);
  if (windowBlock) {
    // Anything between the window and startReactNative belongs to some other
    // plugin; dropping it silently would ship a build without it.
    const unknown = windowBlock[1]
      .split("\n")
      .map((l) => l.trim())
      .filter((l) => l);
    if (unknown.length) fail(`unexpected code inside the window/startReactNative block: ${unknown.join(" | ")}`);
    out = out.replace(WINDOW_BLOCK, "\n");
  } else if (/startReactNative\(/.test(out)) {
    fail("AppDelegate.swift still starts React Native but the SDK 57 window block was not recognised; update the plugin for this template.");
  }

  // Left in place these overrides still work (ExpoAppSceneDelegate dedupes the
  // RCTLinkingManager call), so a template drift only warrants a warning.
  out = out.replace(LINKING_OVERRIDE, "\n").replace(UNIVERSAL_LINK_OVERRIDE, "\n");
  if (/open url: URL,/.test(out)) warn("the openURL override in AppDelegate.swift was not recognised and was left in place.");
  if (/continue userActivity: NSUserActivity,/.test(out)) {
    warn("the continueUserActivity override in AppDelegate.swift was not recognised and was left in place.");
  }

  out = out.replace(/\n{3,}/g, "\n\n").replace(/\n\n(\}\n)/g, "\n$1");
  return out;
}

function deepEqual(a, b) {
  if (a === b) return true;
  if (typeof a !== "object" || typeof b !== "object" || a === null || b === null) return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  const ka = Object.keys(a);
  const kb = Object.keys(b);
  return ka.length === kb.length && ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && deepEqual(a[k], b[k]));
}

function applySceneManifest(infoPlist) {
  const current = infoPlist.UIApplicationSceneManifest;
  if (current === undefined) {
    infoPlist.UIApplicationSceneManifest = structuredClone(SCENE_MANIFEST);
  } else if (!deepEqual(current, SCENE_MANIFEST)) {
    fail("Info.plist already has a different UIApplicationSceneManifest; merge it into the plugin instead of overwriting it.");
  }
  return infoPlist;
}

function writeSceneDelegate(filePath) {
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, "utf8");
    if (existing === SCENE_DELEGATE_SOURCE) return false;
    if (!existing.startsWith(SCENE_DELEGATE_MARKER)) {
      fail(`${filePath} exists and was not generated by this plugin; refusing to overwrite it.`);
    }
  }
  fs.writeFileSync(filePath, SCENE_DELEGATE_SOURCE);
  return true;
}

function addSceneDelegateToProject(project, projectName) {
  // Same lookup addBuildSourceFileToGroup uses (a child of the main group):
  // after pod install a second "zerospike" group exists under Pods.
  const mainGroup = project.getPBXGroupByKey(project.getFirstProject().firstProject.mainGroup);
  const groupRef = mainGroup.children.find((child) => child.comment === projectName);
  const group = groupRef && project.getPBXGroupByKey(groupRef.value);
  if (!group) fail(`PBXGroup "${projectName}" not found under the main group.`);
  if (group.children.some((child) => child.comment === SCENE_DELEGATE_FILE)) return false;

  // The watch app from @bacons/apple-targets is also an application product,
  // so resolve the main target by name rather than by product type.
  const targetUuid = project.findTargetKey(projectName);
  if (!targetUuid) fail(`native target "${projectName}" not found.`);
  IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
    filepath: `${projectName}/${SCENE_DELEGATE_FILE}`,
    groupName: projectName,
    project,
    targetUuid,
  });
  return true;
}

function withSceneManifest(config) {
  return withInfoPlist(config, (c) => {
    applySceneManifest(c.modResults);
    return c;
  });
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (c) => {
    if (c.modResults.language !== "swift") fail(`AppDelegate language "${c.modResults.language}" is not supported.`);
    c.modResults.contents = transformAppDelegate(c.modResults.contents);
    return c;
  });
}

function withSceneDelegateFile(config) {
  return withXcodeProject(config, (c) => {
    const { projectName, platformProjectRoot } = c.modRequest;
    writeSceneDelegate(path.join(platformProjectRoot, projectName, SCENE_DELEGATE_FILE));
    addSceneDelegateToProject(c.modResults, projectName);
    return c;
  });
}

function withSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withSceneAppDelegate(config);
  config = withSceneDelegateFile(config);
  return config;
}

module.exports = withSceneLifecycle;
module.exports.transformAppDelegate = transformAppDelegate;
module.exports.applySceneManifest = applySceneManifest;
module.exports.writeSceneDelegate = writeSceneDelegate;
module.exports.addSceneDelegateToProject = addSceneDelegateToProject;
module.exports.SCENE_MANIFEST = SCENE_MANIFEST;
module.exports.SCENE_DELEGATE_SOURCE = SCENE_DELEGATE_SOURCE;
