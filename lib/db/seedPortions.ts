/**
 * Household measures for the catalog's most-used foods, kept out of ./seed.ts
 * (a 400 KB literal) as a name-keyed overlay that seed.ts folds in. Each entry
 * carries its source:
 *
 *   usda  USDA FoodData Central household measure (public domain) for the
 *         same food in its cooked / ready-to-eat form where the catalog's
 *         carb figure is for that form.
 *   std   a widely used package or standard serving (a bottle, a can, a
 *         bakery piece) where USDA has no single household measure.
 *
 * usda grams were compared with SR Legacy / FNDDS household measures
 * (docs/food-sources.md); where those two disagree the SR Legacy figure is kept
 * unless noted there. std grams are conventions, not USDA values. Where no
 * gram value is established there is no entry, and the food keeps the plain
 * gram field. Labels are the closed set in ./types (PortionLabelKey): no new
 * label, so no migration. The key is the catalog's English name.
 */
import type { PortionLabelKey } from "./types";

export type PortionSource = "usda" | "std";

export type PortionPair = readonly [PortionLabelKey, number];

export interface PortionOverlay {
  src: PortionSource;
  portions: readonly PortionPair[];
}

const u = (...portions: PortionPair[]): PortionOverlay => ({ src: "usda", portions });
const s = (...portions: PortionPair[]): PortionOverlay => ({ src: "std", portions });

